// All configuration comes from the environment (see ../.env.example).
function str(name: string, fallback?: string): string {
  const v = process.env[name];
  if (v === undefined || v === '') {
    if (fallback === undefined) throw new Error(`missing env ${name}`);
    return fallback;
  }
  return v;
}
const bool = (name: string, fallback = false) => {
  const v = process.env[name];
  return v === undefined || v === '' ? fallback : ['1', 'true', 'yes'].includes(v.toLowerCase());
};

const production = process.env.NODE_ENV === 'production';

